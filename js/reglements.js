/* Tableau 19 : conversion du jet de progression en variation de cote.
   Règle de la ligue : la recote est plafonnée à +3 (et peut descendre à -5). */
const CONVERSION = [[146,4],[136,3],[121,2],[101,1],[71,0],[51,-1],[26,-2],[11,-3],[-19,-4]];
function convertirJet(total){
  for (const [seuil, prog] of CONVERSION){ if (total >= seuil) return Math.min(3, prog); }
  return -5;
}

/* Fourchette de recote des cotes-clés : base 60 + ModA + ModS, aléa Kcheck 1 à 40. */
function fourchetteRecote(j, mods){
  const base = 60 + modA(j) + (mods ?? 0);
  return {base, min: convertirJet(base + 1), max: convertirJet(base + 40)};
}

